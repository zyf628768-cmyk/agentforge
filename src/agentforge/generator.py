"""Generator interface and executable offline WAT/Python engineering backend."""

from __future__ import annotations

import hashlib
from importlib.resources import files as resources
from pathlib import Path
from typing import Protocol

from .core import ForgeError, artifact_destination, write_json
from .spec import validate


class Generator(Protocol):
    """Backends produce files only. Evaluation never trusts their claimed results."""

    def generate(self, spec: dict, destination: Path, variant: str = "correct") -> Path: ...


class OfflineGenerator:
    """Deterministic text-cleaner compiler; no model calls or network access."""

    def generate(self, spec: dict, destination: Path, variant: str = "correct") -> Path:
        validate(spec)
        if variant not in {"correct", "bug", "regression"}:
            raise ForgeError("Unknown compiler variant")
        if destination.exists():
            raise ForgeError("Destination exists; use a new version directory")
        artifact_destination(destination, spec["name"])
        try:
            import wasmtime
        except ImportError as exc:
            raise ForgeError("Install Wasmtime before building; no host-code fallback") from exc
        wat = resources("agentforge").joinpath("data/clean.wat").read_text()
        if variant == "bug":
            # Deterministic defect: fail to recognize TAB as whitespace.
            wat = wat.replace("(i32.const 9)", "(i32.const 10)")
        if variant == "regression":
            wat = wat.replace(
                ";; VARIANT",
                """
          (if (i32.and (i32.ge_u (local.get $c) (i32.const 65))
                       (i32.le_u (local.get $c) (i32.const 90)))
            (then (local.set $c (i32.add (local.get $c) (i32.const 32)))))""",
            )
        wasm = bytes(wasmtime.wat2wasm(wat))
        destination.mkdir(parents=True)
        (destination / "scripts").mkdir()
        (destination / "tests").mkdir()
        (destination / "examples").mkdir()
        (destination / "schemas").mkdir()
        (destination / "scripts/clean.wat").write_text(wat, encoding="utf-8")
        (destination / "scripts/clean.wasm").write_bytes(wasm)
        (destination / "SKILL.md").write_text(
            f"---\nname: {spec['name']}\ndescription: Clean text by collapsing ASCII whitespace; "
            "use for local text normalization while preserving Unicode and case.\n"
            "license: MIT\nmetadata:\n  runtime: AgentForge 0.1 with Wasmtime; no network required\n---\n\n"
            "# Text cleaning\n\nPass a JSON object with a text string on standard input.\n"
            "Run through the trusted AgentForge WASM engine:\n\n"
            "```sh\nagentforge test .\nagentforge run . --input examples/input.json\n```\n\n"
            "The executable is scripts/clean.wasm; do not execute generated Python on the host.\n"
            "See schemas/input.json and examples/ for the contract. ASCII whitespace is collapsed; "
            "other Unicode characters and letter case are preserved.\n",
            encoding="utf-8",
        )
        (destination / "scripts/run.py").write_text(
            '"""Auditable convenience wrapper; not executed by AgentForge tests."""\n'
            "from pathlib import Path\nfrom agentforge.cli import main\n\n"
            'if __name__ == "__main__":\n'
            '    raise SystemExit(main(["run", str(Path(__file__).resolve().parents[1])]))\n',
            encoding="utf-8",
        )
        (destination / "tests/test_skill.py").write_text(
            '"""For use by a reviewer after auditing; engine uses JSON cases directly."""\n'
            "from pathlib import Path\nfrom agentforge.testing import evaluate\n\n"
            "def test_skill():\n"
            "    report = evaluate(Path(__file__).resolve().parents[1])\n"
            '    assert report["status"] == "passed", report\n',
            encoding="utf-8",
        )
        (destination / "README.md").write_text(
            f"# {spec['name']}\n\nExecutable WASM Skill generated by the offline compiler.\n\n"
            "Requires Python 3.11+ and installed agentforge.\n"
            "`agentforge run . --input examples/input.json`\n\n"
            "`agentforge test .` runs the trusted evaluator, including independent holdouts.\n"
            "No external dependencies inside the WASM guest. Never run unaudited generated Python.\n",
            encoding="utf-8",
        )
        write_json(destination / "spec.json", spec)
        write_json(destination / "schemas/input.json", spec["inputs"])
        write_json(destination / "schemas/output.json", spec["outputs"])
        write_json(
            destination / "config.json", {"backend": "wasmtime-no-imports", "max_bytes": 32768}
        )
        write_json(
            destination / "tests/cases.json",
            [
                {
                    "id": "unit-space",
                    "input": {"text": "  hello   world  "},
                    "expected": {"text": "hello world"},
                },
                {"id": "unit-tab", "input": {"text": "a\t\tb"}, "expected": {"text": "a b"}},
                {"id": "unit-empty", "input": {"text": ""}, "expected": {"text": ""}},
            ],
        )
        write_json(destination / "examples/input.json", {"text": "  Hello\t  世界\r\n "})
        write_json(destination / "examples/output.json", {"text": "Hello 世界"})
        write_json(
            destination / "manifest.json",
            {
                "name": spec["name"],
                "version": spec["version"],
                "kind": spec["kind"],
                "source": "offline-deterministic",
                "entrypoint": "scripts/clean.wasm",
                "sha256": hashlib.sha256(wasm).hexdigest(),
                "dependencies": [],
                "compatibility": "agentforge-wasm-abi-1",
                "variant": variant,
            },
        )
        return destination
